-- =============================================================
-- 인물 이미지 편집(크롭 등) 여부 컬럼 추가 (이슈 #219)
--
-- CC BY/BY-SA는 원본을 변형했을 경우 그 사실을 표시할 의무가 있다.
-- 대부분의 이미지는 4:5 크롭 파이프라인을 거쳤지만 일부는 원본을 그대로 썼기 때문에
-- 라이선스만으로는 편집 여부를 판단할 수 없어 별도 컬럼으로 저장한다.
--
-- 기존 행은 DEFAULT TRUE로 채운다 — 실제로 크롭된 경우가 다수(120명 중 최소 97명)라,
-- "편집 안 됨(false)"을 기본값으로 깔면 크롭된 다수가 표시 의무를 누락한 상태로 배포된다.
-- true를 기본값으로 두면 원본을 그대로 쓴 소수 예외만 나중에 false로 고치면 되므로 더 안전하다.
-- 예외 목록은 후속 데이터 점검에서 확인해 업데이트한다(예: 오프라 윈프리(25) 등 "크롭하지마" 지시로 원본 그대로 사용).
--
-- ⚠️ 배포 순서: 이 SQL을 운영 DB에 먼저 적용한 뒤 애플리케이션을 배포할 것.
--    application-prod.yml이 ddl-auto: validate 이므로, 컬럼 없이 배포하면
--    Hibernate 스키마 검증에 실패해 서버가 기동되지 않는다.
-- =============================================================

ALTER TABLE `celebrity`
    ADD COLUMN `is_edited` BOOLEAN NOT NULL DEFAULT TRUE
        COMMENT '원본 이미지를 크롭 등으로 변형했는지 여부. true면 출처표시 문구에 "편집됨" 표기';

